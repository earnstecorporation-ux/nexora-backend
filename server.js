require('dotenv').config();
const express = require('express');
const cors = require('cors');
const crypto = require('crypto');
const Razorpay = require('razorpay');

const app = express();
// Default to 3000, or port from environment if specified
const PORT = process.env.PAYMENT_PORT || (process.env.PORT && process.env.PORT !== '8080' ? process.env.PORT : 3000);

app.use(cors());
app.use(express.json());

// Fixed price for NEXORA Premium: ₹49 INR = 4900 paise (one-time lifetime access)
const NEXORA_PREMIUM_AMOUNT_PAISE = 4900;
const NEXORA_CURRENCY = 'INR';

/**
 * Returns a configured Razorpay client instance using current environment variables.
 */
function getRazorpayClient() {
  const keyId = process.env.RAZORPAY_KEY_ID;
  const keySecret = process.env.RAZORPAY_KEY_SECRET;
  if (!keyId || !keySecret) {
    return null;
  }
  return new Razorpay({
    key_id: keyId,
    key_secret: keySecret
  });
}

/**
 * Health check endpoint
 * GET /api/health
 */
app.get('/api/health', (req, res) => {
  const keyId = process.env.RAZORPAY_KEY_ID || '';
  const keySecret = process.env.RAZORPAY_KEY_SECRET || '';
  const isKeyConfigured = Boolean(keyId && keySecret);
  const mode = keyId ? (keyId.startsWith('rzp_test') ? 'TEST' : 'LIVE') : 'UNCONFIGURED';

  res.json({
    status: 'ok',
    service: 'NEXORA Payment Backend',
    mode: mode,
    keyConfigured: isKeyConfigured,
    product: 'NEXORA Premium Lifetime',
    amount: NEXORA_PREMIUM_AMOUNT_PAISE,
    currency: NEXORA_CURRENCY,
    timestamp: new Date().toISOString()
  });
});

/**
 * Create Order Endpoint
 * POST /api/payment/create-order
 * Request body: { receipt?: string }
 * 
 * Creates a Razorpay order on the backend for exactly ₹49 INR (4900 paise).
 */
app.post('/api/payment/create-order', async (req, res) => {
  try {
    const keyId = process.env.RAZORPAY_KEY_ID;
    const keySecret = process.env.RAZORPAY_KEY_SECRET;

    if (!keyId || !keySecret) {
      console.warn('[NEXORA Backend] Cannot create order: RAZORPAY_KEY_ID or RAZORPAY_KEY_SECRET missing in environment');
      return res.status(503).json({
        success: false,
        error: 'Razorpay credentials not configured on backend. Please configure RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET in the backend environment variables.'
      });
    }

    const client = getRazorpayClient();
    const receipt = req.body.receipt || `nexora_${Date.now()}`;

    const options = {
      amount: NEXORA_PREMIUM_AMOUNT_PAISE, // exactly 4900 paise = ₹49
      currency: NEXORA_CURRENCY,
      receipt: receipt,
      payment_capture: 1,
      notes: {
        product: 'NEXORA Premium Lifetime',
        type: 'one_time',
        entitlement: 'LIFETIME_PREMIUM'
      }
    };

    console.log(`[NEXORA Backend] Creating order with amount ${NEXORA_PREMIUM_AMOUNT_PAISE} ${NEXORA_CURRENCY}...`);
    const order = await client.orders.create(options);

    console.log(`[NEXORA Backend] Order created successfully: ID=${order.id}, Amount=${order.amount} ${order.currency}`);

    res.json({
      success: true,
      orderId: order.id,
      amount: order.amount,
      currency: order.currency,
      keyId: keyId,
      receipt: order.receipt
    });
  } catch (error) {
    console.error('[NEXORA Backend] Failed to create Razorpay order:', error);
    res.status(500).json({
      success: false,
      error: error.message || 'Failed to create Razorpay order on backend'
    });
  }
});

/**
 * Verify Signature Endpoint
 * POST /api/payment/verify-signature
 * Request body: { orderId: string, paymentId: string, signature: string }
 * 
 * Verifies HMAC SHA-256 signature generated by Razorpay Checkout.
 * Formula: HMAC_SHA256(order_id + "|" + payment_id, RAZORPAY_KEY_SECRET) === signature
 */
app.post('/api/payment/verify-signature', (req, res) => {
  try {
    const { orderId, paymentId, signature } = req.body;
    const keySecret = process.env.RAZORPAY_KEY_SECRET;

    if (!orderId || !paymentId || !signature) {
      return res.status(400).json({
        verified: false,
        error: 'Missing required parameters: orderId, paymentId, or signature'
      });
    }

    if (!keySecret) {
      return res.status(503).json({
        verified: false,
        error: 'Backend RAZORPAY_KEY_SECRET is not configured. Cannot verify cryptographic signature.'
      });
    }

    // Cryptographic signature verification
    const text = `${orderId}|${paymentId}`;
    const generatedSignature = crypto
      .createHmac('sha256', keySecret)
      .update(text)
      .digest('hex');

    const isAuthentic = crypto.timingSafeEqual(
      Buffer.from(generatedSignature, 'utf-8'),
      Buffer.from(signature, 'utf-8')
    );

    if (isAuthentic) {
      console.log(`[NEXORA Backend] Signature verified successfully for Order ${orderId}, Payment ${paymentId}`);

      // Generate verification proof token
      const verificationProof = crypto
        .createHmac('sha256', keySecret)
        .update(`NEXORA_ENTITLEMENT:${orderId}:${paymentId}:LIFETIME`)
        .digest('hex');

      return res.json({
        verified: true,
        status: 'PAID',
        orderId: orderId,
        paymentId: paymentId,
        amount: NEXORA_PREMIUM_AMOUNT_PAISE,
        currency: NEXORA_CURRENCY,
        entitlement: 'LIFETIME_PREMIUM',
        entitlementToken: verificationProof,
        verifiedAt: Date.now(),
        message: 'Payment signature verified successfully. Lifetime Premium unlocked.'
      });
    } else {
      console.warn(`[NEXORA Backend] Signature mismatch for Order ${orderId}, Payment ${paymentId}`);
      return res.status(400).json({
        verified: false,
        status: 'FAILED',
        error: 'Invalid payment signature. Payment verification rejected.'
      });
    }
  } catch (error) {
    console.error('[NEXORA Backend] Signature verification error:', error);
    res.status(500).json({
      verified: false,
      error: error.message || 'Internal error verifying payment signature'
    });
  }
});

app.listen(PORT, '0.0.0.0', () => {
  console.log(`[NEXORA Backend] Server listening on port ${PORT}`);
  console.log(`[NEXORA Backend] Health check: http://localhost:${PORT}/api/health`);
});
